UV_VERSION = "0.11.29"
PIP_TARGETS = {
    "linux-64": "x86_64-manylinux_2_17",
    "linux-aarch64": "aarch64-manylinux_2_17",
}


def _write_explicit_lock(path: Path, records: list[dict[str, object]], target: str) -> None:
    entries = []
    for record in records:
        url = record.get("url")
        artifact_sha256 = record.get("sha256")
        if not isinstance(url, str) or not isinstance(artifact_sha256, str) or SHA256_RE.fullmatch(artifact_sha256) is None:
            raise LockValidationError(f"{target}: solver record lacks an exact package URL and SHA-256")
        parsed = urlsplit(url)
        if parsed.scheme != "https" or parsed.netloc != CONDA_FORGE_HOST or not parsed.path.startswith(CONDA_FORGE_PATH):
            raise LockValidationError(f"{target}: solver returned a non-conda-forge package URL {url!r}")
        entries.append(f"{url}#{artifact_sha256}")
    python_records = [record for record in records if record.get("name") == "python"]
    if len(python_records) != 1 or python_records[0].get("version") != PYTHON_VERSION:
        raise LockValidationError(f"{target}: solver did not select Python {PYTHON_VERSION}")
    path.write_text(
        "# Generated by scripts/generate_release_dependency_locks.py; review before committing.\n"
        "# Conda explicit format: no dependency solve is performed during consumption.\n"
        "@EXPLICIT\n"
        + "\n".join(sorted(set(entries)))
        + "\n"
    )


def conda_specs_from_environment(environment: Path) -> list[str]:
    """Read only the top-level Conda dependency specifications from the source recipe."""
    package_specs = []
    in_dependencies = False
    for line in environment.read_text().splitlines():
        if line == "dependencies:":
            in_dependencies = True
            continue
        if in_dependencies and line and not line.startswith((" ", "#")):
            break
        if not in_dependencies:
            continue
        if not line.startswith("  - "):
            continue
        spec = line.removeprefix("  - ").strip()
        if spec and not spec.endswith(":") and not spec.startswith("#"):
            package_specs.append(spec)
    return package_specs


def _solver_record_identity(record: dict[str, object]) -> tuple[object, ...]:
    try:
        name = record["name"]
        version = record["version"]
    except KeyError as error:
        raise LockValidationError(f"solver record missing identity field {error.args[0]}") from error
    if not isinstance(name, str) or not isinstance(version, str):
        raise LockValidationError("solver record identity name and version must be strings")
    build = record.get("build", record.get("build_string"))
    subdir = record.get("subdir", record.get("platform"))
    return name, version, build, record.get("build_number"), subdir


def _solve_target(conda: str, environment: Path, temp_root: Path, target: str) -> list[dict[str, object]]:
    prefix = temp_root / f"hummingbot-{target}"
    environment_variables = os.environ.copy()
    environment_variables["CONDA_OVERRIDE_GLIBC"] = "2.17"
    environment_variables["CONDA_PKGS_DIRS"] = str(temp_root / "conda-pkgs")
    package_specs = conda_specs_from_environment(environment)
    if not package_specs:
        raise LockValidationError(f"{environment}: no Conda package specifications found")
    result = subprocess.run(
        [
            conda,
            "create",
            "--dry-run",
            "--json",
            "--override-channels",
            "--channel",
            "conda-forge",
            "--prefix",
            str(prefix),
            "--platform",
            target,
            *package_specs,
        ],
        check=False,
        capture_output=True,
        text=True,
        env=environment_variables,
    )
    if result.returncode != 0:
        raise LockValidationError(f"{target}: Conda solve failed: {result.stderr.strip() or result.stdout.strip()}")
    try:
        payload = json.loads(result.stdout)
        fetch_records = payload["actions"]["FETCH"]
        link_records = payload["actions"]["LINK"]
    except (json.JSONDecodeError, KeyError, TypeError) as error:
        raise LockValidationError(f"{target}: Conda dry-run did not return complete FETCH records") from error
    if not isinstance(fetch_records, list) or not isinstance(link_records, list) or not link_records:
        raise LockValidationError(f"{target}: Conda dry-run returned no package records")
    fetch = {_solver_record_identity(record): record for record in fetch_records}
    linked_identities = [_solver_record_identity(record) for record in link_records]
    linked = set(linked_identities)
    if len(fetch) != len(fetch_records) or len(linked) != len(link_records) or set(fetch) != linked:
        raise LockValidationError(f"{target}: isolated package cache did not produce a complete link plan")
    return [fetch[identity] for identity in linked_identities]


def _pip_lock_from_downloads(python: str, temp_root: Path) -> str:
    download_dir = temp_root / "pip-downloads"
    download_dir.mkdir()
    requirements = [f"{name}=={version}" for name, version in EIP712_DIRECT_REQUIREMENTS.items()]
    result = subprocess.run(
        [python, "-m", "pip", "download", "--isolated", "--no-cache-dir", "--index-url", PYPI_INDEX, "--no-deps", "--dest", str(download_dir), *requirements],
        check=False,
        capture_output=True,
        text=True, env={**_resolver_environment(temp_root), "PIP_CONFIG_FILE": os.devnull},
    )
    if result.returncode != 0:
        raise LockValidationError(f"pip download failed: {result.stderr.strip() or result.stdout.strip()}")
    artifacts = sorted(download_dir.iterdir())
    if len(artifacts) != 1:
        raise LockValidationError("pip download did not produce exactly the direct locked inputs")
    rendered = []
    for name, version in EIP712_DIRECT_REQUIREMENTS.items():
        normalized = name.replace("-", "_").lower()
        matching = [artifact for artifact in artifacts if artifact.name.lower().replace("-", "_").startswith(normalized)]
        if len(matching) != 1:
            raise LockValidationError(f"pip download missing exact artifact for {name}")
        artifact_sha256 = hashlib.sha256(matching[0].read_bytes()).hexdigest()
        rendered.extend([f"{name}=={version} \\", f"    --hash=sha256:{artifact_sha256}"])
    return "\n".join(rendered) + "\n"


def _resolver_environment(temp_root: Path) -> dict[str, str]:
    environment = {key: value for key, value in os.environ.items() if not key.startswith(("UV_", "PIP_"))}
    environment["UV_CACHE_DIR"] = str(temp_root / "uv-cache")
    return environment


def _injective_lock_from_uv(uv: str, temp_root: Path, target: str, constraints: Path) -> str:
    input_path = temp_root / f"injective-{target}.in"
    output_path = temp_root / f"injective-{target}.lock"
    input_path.write_text("".join(f"{name}=={version}\n" for name, version in INJECTIVE_DIRECT_REQUIREMENTS.items()))
    result = subprocess.run(
        [uv, "pip", "compile", str(input_path), "--constraint", str(constraints), "--python-version", PYTHON_VERSION, "--python-platform", PIP_TARGETS[target], "--generate-hashes", "--no-annotate", "--no-header", "--no-config", "--default-index", PYPI_INDEX, "--output-file", str(output_path)],
        check=False, capture_output=True, text=True, env=_resolver_environment(temp_root),
    )
    if result.returncode != 0:
        raise LockValidationError(f"{target}: uv closure generation failed: {result.stderr.strip() or result.stdout.strip()}")
    return output_path.read_text()


def _validate_uv_version(uv: str) -> None:
    result = subprocess.run([uv, "--version"], check=False, capture_output=True, text=True)
    observed = result.stdout.strip() or result.stderr.strip()
    if result.returncode != 0 or observed.split(maxsplit=2)[:2] != ["uv", UV_VERSION]:
        raise LockValidationError(f"expected uv {UV_VERSION}, got {observed or 'no version output'}")


def _provenance(lock_dir: Path, environment: Path, pip_packages: Path) -> str:
    artifact_names = [f"{target}.explicit.txt" for target in TARGETS] + [f"pip-injective-{target}.lock.txt" for target in TARGETS] + ["pip-eip712-direct.lock.txt"]
    closures = {target: _validate_pip_lock(lock_dir / f"pip-injective-{target}.lock.txt", INJECTIVE_DIRECT_REQUIREMENTS, closure=True) for target in TARGETS}
    overlaps = {}
    for target in TARGETS:
        conda_versions = _conda_package_versions(_explicit_entries(lock_dir / f"{target}.explicit.txt", target))
        overlaps[target] = {name: closures[target][name] for name in sorted(set(conda_versions) & set(closures[target]))}
    payload = {
        "artifacts": {name: hashlib.sha256((lock_dir / name).read_bytes()).hexdigest() for name in artifact_names},
        "format": 1,
        "injective_direct_requirements": INJECTIVE_DIRECT_REQUIREMENTS,
        "origin_policy": ORIGIN_POLICY,
        "pip_closures": closures,
        "conda_pip_overlaps": overlaps,
        "pip_targets": PIP_TARGETS,
        "python_version": PYTHON_VERSION,
        "runtime_substitution": RUNTIME_SUBSTITUTION,
        "sources": {
            "setup/environment.yml": hashlib.sha256(environment.read_bytes()).hexdigest(),
            "setup/pip_packages.txt": hashlib.sha256(pip_packages.read_bytes()).hexdigest(),
        },
        "targets": list(TARGETS),
        "uv_version": UV_VERSION,
    }
    return json.dumps(payload, indent=2, sort_keys=True) + "\n"


def generate_locks(lock_dir: Path, environment: Path, pip_packages: Path, conda: str, python: str, uv: str) -> None:
    """Generate each target in temporary storage, then create a new lock directory."""
    if lock_dir.exists():
        raise LockValidationError(f"refusing to overwrite existing lock directory {lock_dir}")
    _validate_uv_version(uv)
    with tempfile.TemporaryDirectory(prefix="hummingbot-release-locks-") as temporary:
        temporary_root = Path(temporary)
        staged_locks = temporary_root / "locks"
        staged_locks.mkdir()
        for target in TARGETS:
            _write_explicit_lock(staged_locks / f"{target}.explicit.txt", _solve_target(conda, environment, temporary_root, target), target)
        for target in TARGETS:
            conda_versions = _conda_package_versions(_explicit_entries(staged_locks / f"{target}.explicit.txt", target))
            constraints = temporary_root / f"{target}.constraints.txt"
            constraints.write_text("".join(f"{name}=={version}\n" for name, version in sorted(conda_versions.items()) if name[0].isalnum()))
            (staged_locks / f"pip-injective-{target}.lock.txt").write_text(_injective_lock_from_uv(uv, temporary_root, target, constraints))
        (staged_locks / "pip-eip712-direct.lock.txt").write_text(_pip_lock_from_downloads(python, temporary_root))
        (staged_locks / "provenance.json").write_text(_provenance(staged_locks, environment, pip_packages))
        validate_lock_directory(staged_locks, environment, pip_packages)
        staged_locks.rename(lock_dir)


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--lock-dir", type=Path, default=Path("setup/locks"))
    parser.add_argument("--environment", type=Path, default=Path("setup/environment.yml"))
    parser.add_argument("--pip-packages", type=Path, default=Path("setup/pip_packages.txt"))
    parser.add_argument("--conda", default="conda")
    parser.add_argument("--python", default=os.sys.executable)
    parser.add_argument("--uv", default="uv")
    args = parser.parse_args()
    generate_locks(args.lock_dir, args.environment, args.pip_packages, args.conda, args.python, args.uv)
    print(f"generated locks for {', '.join(TARGETS)} in {args.lock_dir}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
